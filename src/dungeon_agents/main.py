class DebugState:
    """A tiny mutable holder for the debug flag.

    Mutable (not a bool) so the in-game `debug` command can toggle it at runtime
    and the already-built hooks see the change without rebuilding the agent.
    """

    def __init__(self, enabled: bool) -> None:
        self.enabled = enabled


def _build_tool_hooks(debug: DebugState):
    """Build run hooks that surface each tool call — only when debug is on.

    The tools run *inside* the SDK's turn, so by default the player only sees the
    narrated result, never the mechanic. Hooks are the SDK's official
    observability seam: the runtime calls `on_agent_start` / `on_tool_start` /
    `on_tool_end` around the agent's work. In debug mode we print which agent is
    acting, each tool call with its arguments, and how long it took — the "see the
    guts" view. Off by default so normal play stays clean. This is exactly the
    audit-the-agent observability we'll want in TestOps AI, and it scales to M6:
    when multiple agents collaborate, on_agent_start shows which one is working.

    Built lazily inside a function so importing this module never requires the SDK.
    """
    from time import perf_counter

    from agents import RunHooks

    # Plain ASCII only: Windows' cp1252 console can't encode emoji/fancy glyphs,
    # and a raised UnicodeEncodeError inside a hook aborts the whole tool call.
    class ToolActivityHooks(RunHooks):
        def __init__(self) -> None:
            self._started: dict[int, float] = {}

        async def on_agent_start(self, context, agent) -> None:
            if debug.enabled:
                console.print(f"[dim][debug] agent [bold]{agent.name}[/bold] is working…[/dim]")

        async def on_tool_start(self, context, agent, tool) -> None:
            if debug.enabled:
                self._started[id(tool)] = perf_counter()
                console.print(f"[dim][debug] {agent.name} -> tool [bold]{tool.name}[/bold]…[/dim]")

        async def on_tool_end(self, context, agent, tool, result) -> None:
            if debug.enabled:
                started = self._started.pop(id(tool), None)
                took = f" ({(perf_counter() - started) * 1000:.0f} ms)" if started else ""
                console.print(f"[dim][debug]   {tool.name} -> {result}{took}[/dim]")

    return ToolActivityHooks()


def run() -> None:
    """Run the interactive game loop until the player exits."""
    settings = load_settings()

    if not settings.has_api_key:
        console.print(
            f"[bold red]No {settings.api_key_env_name} found.[/bold red] "
            f"(provider: [cyan]{settings.provider}[/cyan]) "
            "Copy [cyan].env.example[/cyan] to [cyan].env[/cyan] and add your key, "
            "then run again."
        )
        return

    # The SDK import is heavy (several seconds on first run) and blocks silently.
    # Show a status so the console doesn't look frozen — otherwise the first
    # launch feels like a hang. Imported lazily so the "no key" message above
    # never trips over a missing SDK.
    with console.status("[dim]Loading the game engine (first run can take a moment)…[/dim]"):
        from agents import Runner

        from dungeon_agents.agents.character_judge import build_character_judge
        from dungeon_agents.agents.critic import build_critic

        game_master = build_game_master(settings)
        critic = build_critic(settings)
        # Output-side safety reviewer (M7): flags a scene that broke character or
        # leaked the assistant's nature, triggering a regeneration in _play_turn.
        character_judge = build_character_judge(settings)
        debug = DebugState(enabled=settings.debug)
        tool_hooks = _build_tool_hooks(debug)

    # ASCII-art title splash, then a compact welcome panel. The full how-to-play
    # is NOT shown automatically — the panel points to `help` for players who want
    # it, keeping the startup clean.
    _print_banner()
    debug_note = "  |  debug ON" if debug.enabled else ""
    console.print(
        Panel(
            "[bold]Dungeon Agents[/bold]  -  a free-text fantasy adventure\n"
            "Type [cyan]help[/cyan] for how to play, [cyan]new[/cyan] to start over, "
            "or [cyan]exit[/cyan] to quit.\n"
            f"[dim]{settings.provider} - {settings.model}{debug_note}[/dim]",
            border_style="green",
        )
    )

    # Startup choice. If a saved game exists, ask whether to continue it or start
    # a fresh one (starting fresh discards the current game, so we confirm first).
    # With no save, jump straight into a new adventure — no menu to slow down a
    # first-time player. `_last_scene` tracks what to re-show after a meta-command
    # so the player never loses their place.
    saved = game_state.load_state_or_none()
    resuming = False
    if saved is not None:
        console.print(
            Panel(
                "A saved adventure was found.\n"
                "Type [cyan]continue[/cyan] to resume it, or [cyan]new[/cyan] to "
                "start over.",
                title="Welcome back",
                border_style="green",
            )
        )
        choice = ""
        while choice not in {"continue", "c", "new", "n"}:
            try:
                choice = console.input(
                    "[bold cyan]Load saved game?[/bold cyan] [dim](continue/new)[/dim]: "
                ).strip().lower()
            except (EOFError, KeyboardInterrupt):
                console.print("\n[dim]Farewell, adventurer.[/dim]")
                return
        if choice in {"continue", "c"}:
            resuming = True

    if resuming:
        _resume_banner(saved)
        conversation: list = [{"role": "user", "content": RESUME_PROMPT}]
        _last_scene = saved.last_scene
    else:
        # Starting fresh: if there was a save, confirm before discarding it.
        if saved is not None and not _confirm(
            "Start a new adventure? Your current game will be lost."
        ):
            # Player backed out — resume the existing game instead of losing it.
            _resume_banner(saved)
            conversation = [{"role": "user", "content": RESUME_PROMPT}]
            _last_scene = saved.last_scene
        else:
            game_state.clear_state()  # discard the old game explicitly
            _start_new_game()
            conversation = [{"role": "user", "content": OPENING_PROMPT}]
            _last_scene = ""

    # Play the opening scene once, up front. From here on the loop only generates
    # a new scene in response to a real player ACTION — meta-commands (stats,
    # inventory, help, ...) are pure state reads that re-show the current scene
    # without spending a model call or re-running the Critic.
    _last_scene, conversation, outcome = _play_turn(
        game_master, critic, character_judge, Runner, conversation, debug, tool_hooks
    )
    if outcome is not None:
        _print_end_of_game(outcome)
        return

    while True:
        try:
            # The label hints that free-form actions are allowed, not just the
            # numbered choices the Game Master lists.
            player_input = console.input(
                "[bold cyan]You[/bold cyan] [dim](action, choice #, or help/new/exit)[/dim]: "
            ).strip()
        except (EOFError, KeyboardInterrupt):
            console.print("\n[dim]Farewell, adventurer.[/dim]")
            return

        if player_input.lower() in EXIT_WORDS:
            console.print("[dim]Farewell, adventurer.[/dim]")
            return
        if player_input.lower() in HELP_WORDS:
            # Meta-command: show help without spending a turn, then re-show the
            # current scene so the player can pick up exactly where they were.
            _print_help()
            if _last_scene:
                _print_scene(_last_scene)
            continue
        if player_input.lower() in NEW_WORDS:
            # Starting fresh discards the current game — confirm first.
            if not _confirm("Start a new adventure? Your current game will be lost."):
                console.print("[dim]Keeping your current adventure.[/dim]")
                if _last_scene:
                    _print_scene(_last_scene)
                continue
            # Reset to a seeded starter state (so stats/inventory work right away),
            # then play a fresh opening scene.
            game_state.clear_state()
            _start_new_game()
            console.print("[dim]Starting a new adventure...[/dim]")
            conversation = [{"role": "user", "content": OPENING_PROMPT}]
            _last_scene, conversation, outcome = _play_turn(
                game_master, critic, character_judge, Runner, conversation, debug, tool_hooks
            )
            if outcome is not None:
                _print_end_of_game(outcome)
                return
            continue
        if player_input.lower() in STATS_WORDS:
            # Meta-command: show deterministic stats, then re-show the scene.
            _print_status()
            if _last_scene:
                _print_scene(_last_scene)
            continue
        if player_input.lower() in INVENTORY_WORDS:
            _print_status(inventory_only=True)
            if _last_scene:
                _print_scene(_last_scene)
            continue
        if player_input.lower() in SUMMARY_WORDS:
            # Show the running story recap, then re-show the scene.
            _print_summary()
            if _last_scene:
                _print_scene(_last_scene)
            continue
        if player_input.lower() in DEBUG_WORDS:
            # Toggle the "see the guts" view at runtime, without a game turn.
            debug.enabled = not debug.enabled
            console.print(
                f"[dim]Debug mode {'ON' if debug.enabled else 'OFF'}.[/dim]"
            )
            continue
        # save/load take a name argument ("save battle"), so match on first word.
        first_word = player_input.split(maxsplit=1)[0].lower() if player_input else ""
        if first_word in SAVES_WORDS:
            # List named checkpoints, then re-show the scene.
            _list_checkpoints()
            if _last_scene:
                _print_scene(_last_scene)
            continue
        if first_word in SAVE_WORDS:
            # Save a named checkpoint: current state + conversation, restored exactly.
            parts = player_input.split(maxsplit=1)
            if len(parts) < 2 or not parts[1].strip():
                console.print("[dim]Usage: [cyan]save <name>[/cyan] (e.g. save battle).[/dim]")
            else:
                _save_checkpoint(parts[1].strip(), conversation)
            if _last_scene:
                _print_scene(_last_scene)
            continue
        if first_word in LOAD_WORDS:
            # Load a named checkpoint: restore state AND conversation exactly.
            parts = player_input.split(maxsplit=1)
            if len(parts) < 2 or not parts[1].strip():
                console.print("[dim]Usage: [cyan]load <name>[/cyan]. See [cyan]saves[/cyan].[/dim]")
                continue
            slot = game_state.load_checkpoint(parts[1].strip())
            if slot is None:
                console.print(
                    f"[dim]No checkpoint named '{parts[1].strip()}' "
                    "(or it was incompatible).[/dim]"
                )
                continue
            # Restore: make this checkpoint the current game and resume its exact
            # conversation, so the Game Master keeps its full memory.
            game_state.save_state(slot.state)
            conversation = slot.conversation or [{"role": "user", "content": RESUME_PROMPT}]
            _last_scene = slot.state.last_scene
            console.print(f"[dim]Loaded checkpoint '{slot.name}'.[/dim]")
            _resume_banner(slot.state)
            continue
        if not player_input:
            continue

        # A real action: add it to the history and play a turn (GM + Critic).
        # This is the ONLY place a player action triggers scene generation.
        conversation.append({"role": "user", "content": player_input})
        scene, next_conversation, outcome = _play_turn(
            game_master, critic, character_judge, Runner, conversation, debug, tool_hooks
        )
        if scene is None:
            # Turn refused by a guardrail (e.g. prompt injection). Drop the blocked
            # message so it never poisons the history, then re-show the current
            # scene so the player can pick up exactly where they were (same as a
            # meta-command). Nothing about the game state advanced.
            conversation.pop()
            if _last_scene:
                _print_scene(_last_scene)
            continue
        _last_scene, conversation = scene, next_conversation
        if outcome is not None:
            _print_end_of_game(outcome)
            return


def main() -> None:
    """Console-script entry point (see pyproject `[project.scripts]`)."""
    run()


if __name__ == "__main__":
    main()

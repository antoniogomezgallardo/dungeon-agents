console = Console()


def _print_scene(text: str) -> None:
    """Render a Game Master reply as Markdown inside a titled panel."""
    console.print(Panel(Markdown(text), title="Game Master", border_style="magenta"))


def _print_status(*, inventory_only: bool = False) -> None:
    """Print the player's stats and/or inventory, read from the saved state.

    Deterministic on purpose: this reads the validated GameState directly rather
    than asking the Game Master to narrate it, so the numbers are always exact
    and consistent (never improvised by the model). If there's no save yet,
    there's nothing to show — say so plainly.
    """
    from dungeon_agents.domain import rules

    state = game_state.load_state_or_none()
    if state is None:
        console.print("[dim]No character yet - take an action to begin.[/dim]")
        return

    if not inventory_only:
        p = state.player
        quest = state.active_quest.title if state.active_quest else "not set yet"
        done = " (completed)" if state.active_quest and state.active_quest.completed else ""
        # A brand-new game starts with a neutral "unknown" location until the
        # Game Master's first scene sets it; show that gently.
        where = state.location if state.location != "unknown" else "not set yet"
        lines = [
            f"[bold]{p.name}[/bold]",
            f"HP:    {p.hp}/{p.max_hp}",
            f"Gold:  {p.gold}",
            f"Where: {where}",
            f"Quest: {quest}{done}",
        ]
        console.print(Panel("\n".join(lines), title="Stats", border_style="blue"))

    # get_inventory returns a ready-made, deterministic summary (from M4 rules).
    console.print(Panel(rules.get_inventory(state), title="Inventory", border_style="blue"))


def _print_summary() -> None:
    """Print the running story summary, read from the saved state.

    Deterministic: shows the `session_summary` the Game Master has been keeping,
    verbatim — not a freshly improvised recap. Empty early on, before anything
    story-significant has happened.
    """
    state = game_state.load_state_or_none()
    if state is None:
        console.print("[dim]No adventure yet - take an action to begin.[/dim]")
        return
    text = state.session_summary or "Nothing notable has happened yet."
    console.print(Panel(text, title="Story so far", border_style="cyan"))


def _start_new_game() -> None:
    """Seed and save a fresh starter GameState.

    Writing the starter state to disk immediately (rather than waiting for the
    first tool call to create it) means stats/inventory always have something to
    show from turn 0 — no "no character yet". Reuses the tools layer's
    `new_game_state()` so the starter hero/quest stay defined in one place.
    """
    from dungeon_agents.tools.game_tools import new_game_state

    game_state.save_state(new_game_state())


def _confirm(question: str) -> bool:
    """Ask a yes/no question at the console; default is No (safe for destructive ops).

    Returns True only on an explicit yes. EOF/Ctrl+C counts as No so an
    accidental interrupt never triggers a destructive action.
    """
    try:
        answer = console.input(f"[yellow]{question} [dim](y/N)[/dim]: [/yellow]").strip()
    except (EOFError, KeyboardInterrupt):
        return False
    return answer.lower() in {"y", "yes"}


def _save_checkpoint(name: str, conversation: list) -> None:
    """Save a named checkpoint (current state + conversation) from the console."""
    from dungeon_agents.domain.models import SaveSlot
    from dungeon_agents.domain.state import StateError

    state = game_state.load_state_or_none()
    if state is None:
        console.print("[dim]Nothing to save yet - take an action first.[/dim]")
        return
    try:
        slot = SaveSlot(name=name, state=state, conversation=conversation)
        msg = game_state.save_checkpoint(slot)
    except StateError as exc:
        console.print(f"[red]{exc}[/red]")
        return
    console.print(f"[dim]{msg}[/dim]")


def _list_checkpoints() -> None:
    """Print the names of saved checkpoints, or a note if there are none."""
    names = game_state.list_checkpoints()
    if not names:
        console.print("[dim]No saved checkpoints yet. Use [cyan]save <name>[/cyan].[/dim]")
        return
    listed = "\n".join(f"- {n}" for n in names)
    console.print(Panel(listed, title="Saved checkpoints", border_style="blue"))


def _remember_last_scene(scene: str) -> None:
    """Persist the Game Master's latest scene into the saved state (best-effort).

    Stored so a resumed game can reprint the exact scene the player was on — the
    deterministic resume from M5. Best-effort: if there's no valid save yet
    (nothing to attach the scene to), we skip silently; the next in-game save
    will capture state going forward.
    """
    current = game_state.load_state_or_none()
    if current is None:
        return
    current.last_scene = scene
    game_state.save_state(current)


def _check_end_of_game(state=None):
    """Return an end-of-game outcome from the validated state, or None.

    Deterministic: victory and defeat are decided by tested rules over the
    GameState (`is_game_won` / `is_game_over`), never by the narrator. The Game
    Master may describe a dramatic fall, but whether the game is actually OVER is
    read from the tracked HP and quest — the last and clearest application of the
    project's core rule that outcomes live in code, not in the story.

    Args:
        state: The GameState to judge. Defaults to the saved state (what the game
            loop uses); tests inject one directly for deterministic checks.

    Returns one of "won", "lost", or None (game continues). "lost" takes
    precedence: a fallen hero can't also have just won.
    """
    from dungeon_agents.domain import rules

    if state is None:
        state = game_state.load_state_or_none()
    if state is None:
        return None
    if rules.is_game_over(state):
        return "lost"
    if rules.is_game_won(state):
        return "won"
    return None


def _print_end_of_game(outcome: str) -> None:
    """Print the win/lose panel that ends the adventure."""
    if outcome == "won":
        console.print(
            Panel(
                "[bold]Victory![/bold] You have completed your quest. "
                "Your adventure ends in triumph.",
                title="The End",
                border_style="green",
            )
        )
    else:  # "lost"
        console.print(
            Panel(
                "[bold]You have fallen.[/bold] Your HP reached 0 and your "
                "adventure ends here.",
                title="Game Over",
                border_style="red",
            )
        )
    console.print(
        "[dim]Type [cyan]new[/cyan] next time to begin a fresh adventure.[/dim]"
    )


def _state_for_review() -> str:
    """Build a compact, factual snapshot of the tracked state for the Critic.

    Deterministic: read straight from the validated GameState so the Critic checks
    the scene against hard facts, not the model's memory. Empty-safe when there's
    no save yet.
    """
    from dungeon_agents.domain import rules

    state = game_state.load_state_or_none()
    if state is None:
        return "No tracked state yet."
    p = state.player
    quest = state.active_quest.title if state.active_quest else "none"
    where = state.location if state.location != "unknown" else "unset"
    return (
        f"HP: {p.hp}/{p.max_hp}; Gold: {p.gold}; Location: {where}; "
        f"Quest: {quest}. {rules.get_inventory(state)}"
    )


def _review_scene(critic, runner, scene: str, debug: DebugState) -> str | None:
    """Ask the Critic whether `scene` is consistent with the tracked state.

    Returns None if consistent (OK), or a short reason string if the Critic found
    a contradiction. The Critic's verdict is a STRUCTURED token ("OK" / "PROBLEM:
    ...") so this code — not another model — decides what to do next.
    """
    from dungeon_agents.agents.critic import CRITIC_PROBLEM_PREFIX

    review_input = [
        {
            "role": "user",
            "content": (
                "Tracked game state:\n"
                f"{_state_for_review()}\n\n"
                "Scene the Game Master just wrote:\n"
                f"{scene}\n\n"
                "Is the scene consistent with the tracked state? Answer OK or "
                "PROBLEM: <reason>."
            ),
        }
    ]
    verdict = runner.run_sync(critic, review_input).final_output.strip()
    if debug.enabled:
        console.print(f"[dim][debug] Critic verdict: {verdict}[/dim]")
    if verdict.upper().startswith(CRITIC_PROBLEM_PREFIX):
        return verdict[len(CRITIC_PROBLEM_PREFIX):].strip() or "unspecified contradiction"
    return None


def _review_character(character_judge, runner, scene: str, debug: DebugState) -> str | None:
    """Ask the Character Judge whether `scene` leaked the assistant's nature.

    The output-side safety check (M7): returns None if the scene stays in
    character, or a short reason if it broke character / leaked its prompt. Like
    the Critic, its verdict is a structured token (IN_CHARACTER / LEAK) so code
    decides. Returns None when no judge is configured (no API key at build time).
    """
    if character_judge is None:
        return None
    from dungeon_agents.agents.character_judge import CHARACTER_LEAK

    verdict = runner.run_sync(character_judge, scene).final_output.strip().upper()
    if debug.enabled:
        console.print(f"[dim][debug] Character Judge verdict: {verdict}[/dim]")
    if verdict.startswith(CHARACTER_LEAK):
        return "the scene broke character or revealed the assistant's nature"
    return None


def _play_turn(game_master, critic, character_judge, runner, conversation, debug, tool_hooks):
    """Run ONE game turn: generate a scene, review it, show it, persist it.

    This is the model-driven part of a turn — the only place that calls the Game
    Master and the Critic. It is invoked for the opening scene and after a real
    player action, but NOT for meta-commands (stats/inventory/help/...), which are
    pure state reads and must never spend a model call or re-run the Critic.

    The Critic reviews the scene against the tracked state before the player sees
    it; on a contradiction the Game Master regenerates, bounded by
    MAX_SCENE_RETRIES so a stubborn Critic can never hang the turn.

    Returns (scene, next_conversation, outcome), where outcome is "won"/"lost" or
    None. The caller shows the end-of-game panel and stops when outcome is set.

    If an input guardrail trips (a prompt-injection attempt), the turn is REFUSED:
    the model never runs, an in-character notice is shown, and (None, conversation,
    None) is returned so the caller keeps the previous scene and state unchanged.
    """
    from agents.exceptions import InputGuardrailTripwireTriggered

    try:
        result = runner.run_sync(game_master, conversation, hooks=tool_hooks)
    except InputGuardrailTripwireTriggered:
        console.print(
            Panel(
                "The Game Master pauses, unmoved. Your attempt to bend the rules "
                "of reality has no effect here - describe an action your character "
                "takes instead.",
                title="Game Master",
                border_style="magenta",
            )
        )
        if debug.enabled:
            console.print("[dim][debug] input guardrail tripped: prompt injection blocked[/dim]")
        return None, conversation, None
    for _ in range(MAX_SCENE_RETRIES):
        # Two independent reviews of the scene before the player sees it:
        # the Critic checks COHERENCE with state, the Character Judge checks
        # SAFETY (no break of character / prompt leak). Either firing triggers a
        # regeneration, bounded by MAX_SCENE_RETRIES.
        problem = _review_scene(critic, runner, result.final_output, debug)
        if problem is None:
            problem = _review_character(character_judge, runner, result.final_output, debug)
        if problem is None:
            break  # scene is consistent and in character — show it
        if debug.enabled:
            console.print(f"[dim][debug] regenerating scene ({problem})[/dim]")
        # Feed the problem back and regenerate from the same context.
        retry_input = result.to_input_list() + [
            {
                "role": "user",
                "content": (
                    "A review flagged your last scene: "
                    f"{problem}. Rewrite the scene so it fits, staying fully in "
                    "character as the Game Master and keeping the same intent and "
                    "choices."
                ),
            }
        ]
        result = runner.run_sync(game_master, retry_input, hooks=tool_hooks)

    scene = result.final_output
    _print_scene(scene)
    _remember_last_scene(scene)  # persist for a deterministic resume
    # End-of-game is decided by tested rules over the validated state, not by the
    # narration. The caller announces it and stops when this is set.
    return scene, result.to_input_list(), _check_end_of_game()


def _resume_banner(state) -> None:
    """Print the deterministic recap + last scene when resuming a saved game."""
    p = state.player
    quest = state.active_quest.title if state.active_quest else "none"
    recap_lines = [
        f"[bold]Resuming your adventure[/bold] as [bold]{p.name}[/bold].",
        f"Location: {state.location}  |  HP: {p.hp}/{p.max_hp}  |  Gold: {p.gold}",
        f"Quest: {quest}",
    ]
    if state.session_summary:
        recap_lines.append(f"\nSo far: {state.session_summary}")
    console.print(Panel("\n".join(recap_lines), title="Recap", border_style="cyan"))
    if state.last_scene:
        # Reprint the exact scene the player left on, verbatim (deterministic).
        _print_scene(state.last_scene)


